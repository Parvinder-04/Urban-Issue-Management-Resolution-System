"""Secure storage for citizen evidence photographs.

Design goals
------------
* Never trust the browser-supplied filename or MIME type. The only accepted
  formats are detected from the file's magic bytes (JPEG, PNG, WebP), and the
  bytes must additionally decode as a real raster image before storage.
* Never write outside the controlled upload directory. Storage keys are
  generated by the server (``evidence/<uuid>.<ext>``) and are always resolved
  back through :func:`resolve_evidence_path`, which rejects absolute paths,
  parent-directory segments and any key outside the evidence directory.
* Enforce the configured ``MAX_UPLOAD_SIZE_MB`` limit.
* Never leave a partial file behind when a write or database operation fails.

The evidence directory is intentionally *not* mounted as public static files.
Authorised downloads go through the authenticated issues router.
"""
from __future__ import annotations

import os
import uuid
from dataclasses import dataclass
from pathlib import Path

from app.core.config import get_settings

EVIDENCE_DIR_NAME = "evidence"

# Detected format -> canonical extension. The extension is chosen by the
# server from the detected bytes, never from the client filename.
FORMAT_EXTENSIONS = {
    "jpeg": ".jpg",
    "png": ".png",
    "webp": ".webp",
}

MEDIA_TYPES = {
    ".jpg": "image/jpeg",
    ".png": "image/png",
    ".webp": "image/webp",
}


class EvidenceStorageError(ValueError):
    """Base error for unsafe or failed evidence storage."""


class EvidenceTooLargeError(EvidenceStorageError):
    """The uploaded evidence exceeds the configured size limit."""


class UnsupportedImageTypeError(EvidenceStorageError):
    """The uploaded bytes are not an explicitly supported image format."""


@dataclass(frozen=True)
class StoredEvidence:
    storage_key: str
    path: Path
    media_type: str
    byte_size: int


def max_upload_bytes() -> int:
    """Return the configured upload limit in bytes."""
    return int(get_settings().MAX_UPLOAD_SIZE_MB) * 1024 * 1024


def upload_root() -> Path:
    """Return the resolved controlled upload root."""
    return Path(get_settings().UPLOAD_DIR).expanduser().resolve()


def detect_image_format(data: bytes) -> str | None:
    """Identify a supported raster format from magic bytes only.

    Returns ``"jpeg"``, ``"png"``, ``"webp"`` or ``None``. SVG, HTML,
    executables and every other format are rejected by returning ``None``.
    """
    if not data:
        return None
    if data.startswith(b"\xff\xd8\xff"):
        return "jpeg"
    if data.startswith(b"\x89PNG\r\n\x1a\n"):
        return "png"
    if len(data) >= 12 and data[:4] == b"RIFF" and data[8:12] == b"WEBP":
        return "webp"
    return None


def media_type_for_path(path: Path) -> str:
    """Return the response media type for a stored evidence file."""
    return MEDIA_TYPES.get(path.suffix.lower(), "application/octet-stream")


def _safe_filename(storage_key: str) -> str:
    """Validate a storage key and return its single filename component.

    Only keys of the exact shape ``evidence/<filename>`` are accepted. Any
    absolute path, drive letter, backslash, ``.``/``..`` segment or nested
    directory is rejected.
    """
    if not isinstance(storage_key, str) or not storage_key.strip():
        raise EvidenceStorageError("Invalid evidence storage key.")

    normalized = storage_key.strip().replace("\\", "/")
    if normalized.startswith("/") or ":" in normalized.split("/")[0]:
        raise EvidenceStorageError("Invalid evidence storage key.")

    parts = [part for part in normalized.split("/") if part not in ("", ".")]
    if len(parts) != 2 or parts[0] != EVIDENCE_DIR_NAME:
        raise EvidenceStorageError("Invalid evidence storage key.")

    filename = parts[1]
    if filename in ("", ".", "..") or "/" in filename or "\\" in filename:
        raise EvidenceStorageError("Invalid evidence storage key.")

    if Path(filename).suffix.lower() not in MEDIA_TYPES:
        raise EvidenceStorageError("Invalid evidence storage key.")
    return filename


def resolve_evidence_path(storage_key: str, base_dir: str | Path | None = None) -> Path:
    """Resolve a stored key to a path that is guaranteed to stay inside the
    controlled evidence directory.

    Raises :class:`EvidenceStorageError` for traversal, absolute paths, legacy
    absolute filesystem paths, or unsupported extensions.
    """
    filename = _safe_filename(storage_key)
    root = (Path(base_dir).expanduser().resolve() if base_dir else upload_root())
    evidence_dir = (root / EVIDENCE_DIR_NAME).resolve()
    candidate = (evidence_dir / filename).resolve()
    if candidate.parent != evidence_dir:
        raise EvidenceStorageError("Invalid evidence storage key.")
    return candidate


def store_evidence(
    data: bytes,
    image_format: str,
    base_dir: str | Path | None = None,
) -> StoredEvidence:
    """Persist validated evidence bytes under a server-generated UUID name.

    The caller must have already detected ``image_format`` from the bytes and
    confirmed that the bytes decode as an image.
    """
    if not data:
        raise EvidenceStorageError("Uploaded file is empty.")
    if len(data) > max_upload_bytes():
        raise EvidenceTooLargeError(
            f"Evidence image exceeds the {get_settings().MAX_UPLOAD_SIZE_MB} MB limit."
        )

    extension = FORMAT_EXTENSIONS.get(image_format)
    if extension is None or detect_image_format(data) != image_format:
        raise UnsupportedImageTypeError(
            "Unsupported file type. Only JPEG, PNG and WebP images are accepted."
        )

    root = (Path(base_dir).expanduser().resolve() if base_dir else upload_root())
    evidence_dir = root / EVIDENCE_DIR_NAME
    try:
        evidence_dir.mkdir(parents=True, exist_ok=True)
    except OSError as exc:
        raise EvidenceStorageError("Could not create the evidence directory.") from exc

    # ``xb`` refuses to overwrite an existing file even in the (vanishingly
    # unlikely) event of a UUID collision.
    for _ in range(5):
        filename = f"{uuid.uuid4().hex}{extension}"
        path = evidence_dir / filename
        try:
            with open(path, "xb") as handle:
                handle.write(data)
                handle.flush()
                os.fsync(handle.fileno())
        except FileExistsError:
            continue
        except OSError as exc:
            _unlink_quietly(path)
            raise EvidenceStorageError("Could not store the evidence image.") from exc

        return StoredEvidence(
            storage_key=f"{EVIDENCE_DIR_NAME}/{filename}",
            path=path,
            media_type=MEDIA_TYPES[extension],
            byte_size=len(data),
        )

    raise EvidenceStorageError("Could not allocate a unique evidence filename.")


def delete_evidence(storage_key: str, base_dir: str | Path | None = None) -> bool:
    """Best-effort removal of a stored evidence file.

    Returns ``True`` when a file was removed. Never raises: cleanup runs on
    error paths and must not mask the original failure.
    """
    try:
        path = resolve_evidence_path(storage_key, base_dir=base_dir)
    except EvidenceStorageError:
        return False
    return _unlink_quietly(path)


def evidence_storage_backend() -> str:
    """Return the configured evidence storage backend.

    ``local`` (default) keeps the existing filesystem behaviour.
    ``database`` stores validated bytes in the application database.
    """
    return os.getenv("EVIDENCE_STORAGE_BACKEND", "local").strip().lower()


def compress_image_bytes(data: bytes, image_format: str) -> bytes:
    """Resize and re-encode an image to conserve database storage.

    The image is decoded through OpenCV, resized so its longest side is at most
    1600 pixels, and re-encoded with a sensible quality setting. If any step
    fails the original bytes are returned unchanged.
    """
    import cv2
    import numpy as np

    if not data:
        return data

    buffer = np.frombuffer(data, dtype=np.uint8)
    if buffer.size == 0:
        return data
    img = cv2.imdecode(buffer, cv2.IMREAD_COLOR)
    if img is None:
        return data

    height, width = img.shape[:2]
    max_dimension = 1600
    if max(height, width) > max_dimension:
        scale = max_dimension / max(height, width)
        img = cv2.resize(
            img,
            (max(1, int(width * scale)), max(1, int(height * scale))),
            interpolation=cv2.INTER_AREA,
        )

    extension = FORMAT_EXTENSIONS.get(image_format)
    if extension is None:
        return data

    if image_format == "jpeg":
        params = [cv2.IMWRITE_JPEG_QUALITY, 85]
    elif image_format == "webp":
        params = [cv2.IMWRITE_WEBP_QUALITY, 85]
    elif image_format == "png":
        params = [cv2.IMWRITE_PNG_COMPRESSION, 9]
    else:
        return data

    ok, encoded = cv2.imencode(extension, img, params)
    if not ok:
        return data
    return bytes(encoded.tobytes())


def _unlink_quietly(path: Path) -> bool:
    try:
        path.unlink()
        return True
    except FileNotFoundError:
        return False
    except OSError:
        return False
